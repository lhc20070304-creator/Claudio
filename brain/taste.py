"""TASTE.PY · 音乐品味蒸馏 — 分析网易云歌单 → AI 生成 taste profile"""
import json
import os
from datetime import datetime
from collections import Counter

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# 延迟导入避免循环
def _get_music():
    from services.music import music
    return music

def _get_brain():
    from brain.claude import brain
    return brain


def collect_user_data(limit_per_playlist=50):
    """收集用户网易云数据：歌单 + 歌曲 + 歌手"""
    music = _get_music()
    if not music.cookie or not music._uid:
        return None, "未登录网易云"

    playlists = music.get_user_playlists()
    if not playlists:
        return None, "未找到歌单"

    # 收集所有歌单的歌曲
    all_songs = []
    playlist_summary = []

    for pl in playlists:
        if pl.get("count", 0) < 3:
            continue
        tracks = music.get_playlist_tracks(pl["id"], limit=min(pl["count"], limit_per_playlist))
        for t in tracks:
            t["_playlist"] = pl["name"]
        all_songs.extend(tracks)
        playlist_summary.append({
            "name": pl["name"],
            "count": pl["count"],
            "fetched": len(tracks),
        })

    # 去重（按 song id）
    seen = {}
    unique_songs = []
    for s in all_songs:
        sid = s.get("id")
        if sid and sid not in seen:
            seen[sid] = True
            unique_songs.append(s)

    # 统计
    artist_counter = Counter()
    for s in unique_songs:
        artist_counter[s.get("artist", "未知")] += 1

    # 加入点赞数据
    from brain.state import state as _state
    likes = _state.conn.execute(
        "SELECT DISTINCT artist, song_name FROM likes ORDER BY id DESC LIMIT 100"
    ).fetchall()
    liked_songs = [{"artist": r[0], "name": r[1], "_playlist": "👍 Liked"} for r in likes]
    # Count liked artists more heavily
    for r in likes:
        artist_counter[r[0]] += 3  # Weight likes 3x

    top_artists = artist_counter.most_common(30)

    return {
        "total_songs": len(unique_songs) + len(liked_songs),
        "total_playlists": len(playlists),
        "playlists": playlist_summary,
        "top_artists": [{"name": a, "count": c} for a, c in top_artists],
        "sample_songs": unique_songs[:80] + liked_songs[:20],
        "liked_count": len(liked_songs),
    }, None


def distill_taste(data, force=False):
    """用 AI 蒸馏品味 → 返回 taste markdown"""
    brain = _get_brain()

    # 组装 prompt
    artists_str = "\n".join(f"- {a['name']}（{a['count']}首）" for a in data["top_artists"][:20])
    playlists_str = "\n".join(f"- {p['name']}（{p['count']}首，采样{p['fetched']}首）" for p in data["playlists"][:15])
    songs_sample = "\n".join(
        f"- {s['artist']} — {s['name']}  [{s.get('_playlist', '')}]"
        for s in data["sample_songs"][:60]
    )

    system_prompt = """你是一个音乐品味分析师。根据用户网易云歌单和收藏数据，生成一份详细的音乐品味档案。

输出格式：纯 Markdown，严格按以下结构：

# 我的音乐品味

## 喜欢的风格
- genre1
- genre2（从歌单和歌手推断）

## 不喜欢的风格
- （如果数据中看不出来，写"暂无数据"）

## 歌手偏好
### 高频收听
- 从 top_artists 中整理

## 场景偏好
- 根据歌单名称和歌曲风格推断

## 数据来源
- 标注分析基于多少首歌、多少个歌单，时间戳

要求：
1. 风格用中英文标注，如"爵士 (Jazz)"
2. 基于实际数据，不要编造
3. 像电台DJ写推荐词一样自然
4. 只输出 Markdown，不要额外解释"""

    user_prompt = f"""## 用户歌单概览
{len(data['playlists'])} 个歌单，共去重后 {data['total_songs']} 首

{playlists_str}

## 高频艺人 Top 20
{artists_str}

## 歌曲采样（60首）
{songs_sample}

请根据以上数据生成音乐品味档案。"""

    result = brain.ask(system_prompt, user_prompt, raw=True)
    taste_md = result.get("say", "") if isinstance(result, dict) else str(result)

    # 如果 AI 返回的是 JSON 包裹的，尝试提取
    if not taste_md or len(taste_md) < 100:
        # fallback: 自己生成
        taste_md = _fallback_taste(data)

    # 加上自动生成标记
    header = f"<!-- AUTO-GENERATED by Claudio Taste Analyzer -->\n<!-- 分析时间: {datetime.now().strftime('%Y-%m-%d %H:%M')} -->\n<!-- 数据来源: {data['total_playlists']}个歌单, {data['total_songs']}首去重歌曲 -->\n\n"
    return header + taste_md


def _fallback_taste(data):
    """当 AI 返回异常时的降级方案"""
    artists = [a["name"] for a in data["top_artists"][:15]]
    playlists = [p["name"] for p in data["playlists"]]

    lines = [
        "# 我的音乐品味",
        "",
        "## 喜欢的风格",
        "（AI 分析中，以下为原始数据摘要）",
        "",
    ]

    # 从歌单名推断风格
    style_keywords = {
        "爵士": "爵士 (Jazz)",
        "jazz": "爵士 (Jazz)",
        "古典": "古典 (Classical)",
        "classical": "古典 (Classical)",
        "钢琴": "钢琴",
        "piano": "钢琴",
        "民谣": "民谣 (Folk)",
        "folk": "民谣 (Folk)",
        "摇滚": "摇滚 (Rock)",
        "rock": "摇滚 (Rock)",
        "pop": "流行 (Pop)",
        "流行": "流行 (Pop)",
        "lofi": "Lo-fi / Chillhop",
        "lo-fi": "Lo-fi / Chillhop",
        "chill": "Lo-fi / Chillhop",
        "bossa": "Bossa Nova",
        "原声": "电影原声 (Soundtrack)",
        "ost": "电影原声 (Soundtrack)",
        "r&b": "R&B",
        "phonk": "Phonk",
        "kp": "K-Pop",
        "epop": "英语流行 (English Pop)",
    }

    found_styles = set()
    for pl_name in playlists:
        name_lower = pl_name.lower()
        for kw, style in style_keywords.items():
            if kw.lower() in name_lower:
                found_styles.add(style)

    for s in sorted(found_styles):
        lines.append(f"- {s}")

    lines += [
        "",
        "## 高频艺人",
    ]
    for a in artists[:12]:
        lines.append(f"- {a}")

    lines += [
        "",
        "## 场景偏好",
        "（待 AI 深入分析）",
        "",
        f"## 数据来源",
        f"- {data['total_playlists']} 个歌单",
        f"- {data['total_songs']} 首去重歌曲",
        f"- 分析时间: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
    ]

    return "\n".join(lines)


def save_taste(markdown):
    """保存品味档案"""
    path = os.path.join(BASE_DIR, "user", "taste.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    # 备份旧文件
    bak = path + ".bak"
    if os.path.exists(path):
        try:
            os.replace(path, bak)
        except Exception:
            pass
    with open(path, "w", encoding="utf-8") as f:
        f.write(markdown)
    return path


def run_taste_analysis(force=False):
    """一键运行：收集 → 蒸馏 → 保存"""
    data, err = collect_user_data()
    if err:
        return {"ok": False, "error": err}

    markdown = distill_taste(data, force=force)
    path = save_taste(markdown)
    return {
        "ok": True,
        "path": path,
        "playlists": len(data["playlists"]),
        "songs": data["total_songs"],
        "artists": len(data["top_artists"]),
    }
